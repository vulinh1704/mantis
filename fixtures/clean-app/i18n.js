window.lumenLang = function lumenLang() {
  return String(navigator.language || 'en').toLowerCase().startsWith('vi') ? 'vi' : 'en';
};

window.t = function t(key) {
  const dict = window.LUMEN_I18N[window.lumenLang()];
  return key in dict ? dict[key] : window.LUMEN_I18N.en[key];
};

window.applyI18n = function applyI18n(titleKey) {
  const lang = window.lumenLang();
  document.documentElement.lang = lang;
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = window.t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', window.t(el.dataset.i18nAria));
  if (titleKey) document.title = window.t(titleKey);
};
